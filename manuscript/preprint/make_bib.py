"""Generate refs.bib for the preprint from refs/references.yaml (the single bibliography source).

Author strings "Surname AB" become "Surname, A. B."; "et al." becomes "and others". Entry type: techreport when a
report number is given, book when a publisher or edition is given without a journal, misc for films, standards and
organisation documents, article otherwise.
Usage (repo root): python3 manuscript/preprint/make_bib.py -> manuscript/preprint/refs.bib
"""
import re
import unicodedata
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SPECIAL = str.maketrans({"&": r"\&", "%": r"\%", "#": r"\#", "_": r"\_"})
# classic BibTeX splits multi-byte UTF-8 when abbreviating names, so non-ASCII is written as LaTeX accents
ACCENTS = {"\u0301": "'", "\u0300": "`", "\u0308": '"', "\u0303": "~", "\u0302": "^", "\u030c": "v", "\u0327": "c",
           "\u0328": "k", "\u030a": "r", "\u0304": "="}
DIRECT = {"ł": r"{\l}", "Ł": r"{\L}", "ø": r"{\o}", "Ø": r"{\O}", "ß": r"{\ss}", "‐": "-", "‑": "-", "–": "--",
          "—": "---", "’": "'", "‘": "`", "“": "``", "”": "''", "µ": r"$\mu$", "μ": r"$\mu$", "×": r"$\times$"}


def ascii_tex(text: str) -> str:
    out = []
    for ch in text:
        if ord(ch) < 128:
            out.append(ch)
        elif ch in DIRECT:
            out.append(DIRECT[ch])
        else:
            base, *marks = unicodedata.normalize("NFD", ch)
            if len(marks) == 1 and marks[0] in ACCENTS and ord(base) < 128:
                out.append("{\\" + ACCENTS[marks[0]] + "{" + base + "}}")  # {\v{c}}: letter accents need braces
            else:
                raise ValueError(f"no LaTeX mapping for {ch!r} (U+{ord(ch):04X}) in {text!r}")
    return "".join(out)


def author(a: str) -> str:
    a = a.strip()
    if a.lower().rstrip(".") in ("et al", "others"):
        return "others"
    a = re.sub(r"\s*\(.*?\)$", "", a)  # drop a role suffix such as "(director)"
    m = re.fullmatch(r"(.+?)\s+([A-ZÀ-Þ](?:-?[A-ZÀ-Þ]){0,3})", a)
    if not m:  # organisation or single name: protect with braces
        return "{" + a + "}"
    surname, initials = m.groups()
    parts = re.findall(r"-?[A-ZÀ-Þ]", initials)  # "H-S" -> H., -S. -> "H.-S."
    out = ""
    for c in parts:
        out += (c + ".") if c.startswith("-") else ((" " if out else "") + c + ".")
    return f"{surname}, {out}"


def entry(key: str, r: dict) -> str:
    if r.get("medium") == "film":
        kind = "misc"
    elif "report" in r:
        kind = "techreport"
    elif "journal" in r:
        kind = "article"
    elif "publisher" in r or "edition" in r:
        kind = "book"
    else:
        kind = "misc"
    f = {}
    if r.get("authors"):
        f["author"] = " and ".join(author(a) for a in r["authors"])
    elif r.get("organization"):
        f["author"] = "{" + r["organization"] + "}"
    for src, dst in (("title", "title"), ("journal", "journal"), ("year", "year"), ("volume", "volume"),
                     ("issue", "number"), ("publisher", "publisher"), ("edition", "edition"),
                     ("booktitle", "booktitle"), ("report", "number"), ("howpublished", "howpublished"),
                     ("doi", "doi")):
        if r.get(src) not in (None, "", "None"):
            f[dst] = str(r[src])
    if r.get("pages"):
        f["pages"] = str(r["pages"]).replace("-", "--")
    if r.get("medium") == "film":  # director as author; studio in howpublished
        f["howpublished"] = f"Film (director); {f.pop('publisher')}"
    if kind == "techreport":
        f["institution"] = r.get("publisher", r.get("organization", "n.a."))
    if "title" in f:  # keep the capitalisation of the source; styles such as unsrtnat lowercase titles otherwise
        f["title"] = "{" + f["title"] + "}"
    body = ",\n".join(f"  {k} = {{{ascii_tex(v.translate(SPECIAL)) if k != 'doi' else v}}}" for k, v in f.items())
    return f"@{kind}{{{key},\n{body}\n}}\n"


def main():
    refs = yaml.safe_load((ROOT / "refs/references.yaml").read_text())["references"]
    out = ROOT / "manuscript/preprint/refs.bib"
    out.write_text("% Generated by make_bib.py from refs/references.yaml. Do not edit by hand.\n\n"
                   + "\n".join(entry(k, v) for k, v in refs.items()))
    print(f"{len(refs)} entries -> {out}")


if __name__ == "__main__":
    main()

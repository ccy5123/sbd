"""Generate the manuscript parameter table (tables/params.tex) from params/params.yaml.

One row per scalar parameter of the model sections listed below: nominal value, range, units and status. Sources and
notes stay in params.yaml (archived with the code), which the table caption points to.
Usage (repo root): python3 manuscript/preprint/make_params_table.py -> manuscript/preprint/tables/params.tex
"""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SECTIONS = {"source": "Source", "odour_thresholds": "Odour thresholds", "jet": "Jet and puff",
            "environment": "Environment", "geometry": "Geometry", "breathing": "Breathing", "acoustics": "Acoustics",
            "perception": "Perception and observers"}
SKIP = {"gamma_lit"}  # superseded (auxiliary hypothesis), kept in params.yaml for the record
UNITS = {"m^3": r"m$^3$", "m^2/s": r"m$^2$\,s$^{-1}$", "m/s": r"m\,s$^{-1}$", "m/s^2": r"m\,s$^{-2}$",
         "umol/L": r"\textmu mol\,L$^{-1}$", "m^3/day": r"m$^3$\,d$^{-1}$", "1/day": r"d$^{-1}$", "1/min": r"min$^{-1}$",
         "dC/C": r"$\Delta C/C$", "-": "--"}


BASIS = {"VERIFIED": "measured", "DERIVED": "derived", "PARTIAL": "partly sourced", "ASSUMPTION": "assumed",
         "NON-PEER-REVIEWED": "non-peer-reviewed source"}

def tex(s) -> str:
    return str(s).replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")


def num(x) -> str:
    if x is None:
        return ""
    if isinstance(x, float) and (abs(x) >= 1e5 or (x != 0 and abs(x) < 1e-3)):
        m, e = f"{x:.2e}".split("e")
        return rf"${float(m):g}\times10^{{{int(e)}}}$"
    return f"{x:g}" if isinstance(x, float) else str(x)


def main():
    p = yaml.safe_load((ROOT / "params/params.yaml").read_text())
    rows = []
    for sec, title in SECTIONS.items():
        rows.append(rf"\multicolumn{{5}}{{l}}{{\textit{{{title}}}}} \\")
        for k, v in p[sec].items():
            if k in SKIP or not isinstance(v, dict) or not isinstance(v.get("value"), (int, float)):
                continue
            lo, hi = v.get("low"), v.get("high")
            rng = f"{num(lo)}--{num(hi)}" if lo is not None and hi is not None and (lo, hi) != (v["value"],) * 2 else ""
            units = UNITS.get(str(v.get("units", "")), tex(v.get("units", "")))
            rows.append(rf"\texttt{{{tex(k)}}} & {num(v['value'])} & {rng} & {units} & {BASIS.get(v.get('status', ''), tex(v.get('status', '')))} \\")
    body = "\n".join(rows)
    out = ROOT / "manuscript/preprint/tables/params.tex"
    out.parent.mkdir(exist_ok=True)
    out.write_text("% Generated by make_params_table.py from params/params.yaml. Do not edit by hand.\n"
                   "\\begin{longtable}{lllll}\n"
                   "\\caption{Model parameters: nominal value, range sampled or tested, and basis: taken from a cited"
                   " measurement, derived from cited data, partly sourced, taken from a non-peer-reviewed source, or assumed. Parameter names are those of the"
                   " code; the source and notes for every entry are in \\texttt{params/params.yaml} of the code"
                   " archive.}\\label{tab:params}\\\\\n"
                   + "\\toprule\nparameter & nominal & range & units & basis \\\\\n\\midrule\n\\endhead\n"
                   + body + "\n\\bottomrule\n\\end{longtable}\n")
    print(f"{body.count(chr(10)) + 1} rows -> {out}")


if __name__ == "__main__":
    main()
